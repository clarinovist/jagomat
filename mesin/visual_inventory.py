def _bekukan(nilai: Any) -> Any:
    """Bekukan mapping/list bersarang agar API tidak membocorkan state mutable."""
    if isinstance(nilai, dict):
        return MappingProxyType({k: _bekukan(v) for k, v in nilai.items()})
    if isinstance(nilai, (list, tuple)):
        return tuple(_bekukan(v) for v in nilai)
    return nilai


def _alasan(template_id: str, bukti: Mapping[str, str]) -> str:
    return f"{template_id}: {bukti['observasi']}"


def _bangun_item(row: tuple[Any, ...]) -> Mapping[str, Any]:
    topik_id, template_id, status, levels, diskriminator, nilai, overrides = row
    if status not in STATUS_VISUAL:
        raise ValueError(f"status visual tidak dikenal: {status!r}")
    try:
        keluarga, observasi, konteks_varian = _BUKTI_TEMPLATE[template_id]
    except KeyError as galat:
        raise ValueError(
            f"bukti klasifikasi belum dideklarasikan: {template_id}"
        ) from galat
    bukti = {
        "keluarga": keluarga,
        "observasi": observasi,
        "konteks_varian": konteks_varian,
        "keputusan": status,
    }
    per_level = {
        level: tuple(overrides.get(level, nilai))
        for level in levels
    }
    item = {
        "topik_id": topik_id,
        "template_id": template_id,
        "status": status,
        "bukti_klasifikasi": bukti,
        "alasan": _alasan(template_id, bukti),
        "deklarasi_varian": {
            "diskriminator": tuple(diskriminator),
            "nilai": tuple(nilai),
        },
        "varian_generator": per_level,
    }
    return _bekukan(item)


_INVENTARIS = tuple(_bangun_item(row) for row in _ROWS)
_BY_TEMPLATE = MappingProxyType({item["template_id"]: item for item in _INVENTARIS})


def identitas_varian(template_id: str, parameter: Mapping[str, Any]) -> str:
    """Identifikasi cabang generator dan tolak varian di luar deklarasi template."""
    try:
        deklarasi = _BY_TEMPLATE[template_id]["deklarasi_varian"]
    except KeyError as galat:
        raise ValueError(f"template {template_id!r} tidak ada di inventaris") from galat
    diskriminator = deklarasi["diskriminator"]
    identitas = "|".join(
        f"{nama}={parameter[nama]}" for nama in diskriminator
    ) if diskriminator else "bawaan"
    if identitas not in deklarasi["nilai"]:
        raise ValueError(
            f"varian {identitas!r} untuk {template_id!r} tidak dideklarasikan"
        )
    return identitas


def inventaris_template() -> tuple[Mapping[str, Any], ...]:
    """Kembalikan view inventaris yang immutable hingga struktur terdalam."""
    return _INVENTARIS


